const express = require('express');
const pool = require('../db');

const router = express.Router();

const VALID_STATUSES = ['Pending', 'In progress', 'Completed'];
const MAX_PG_INT = 2147483647;

/**
 * Validate a record body against the Activity 6 field rules.
 * Returns { errors: [...], value: { title, category, description, status } }
 */
function validateRecord(body) {
  const errors = [];
  const source = body && typeof body === 'object' && !Array.isArray(body) ? body : {};

  function checkText(field, min, max) {
    const raw = source[field];
    if (raw === undefined || raw === null) {
      errors.push(`${field} is required.`);
      return undefined;
    }
    if (typeof raw !== 'string') {
      errors.push(`${field} must be text.`);
      return undefined;
    }
    const text = raw.trim();
    if (text.length < min || text.length > max) {
      errors.push(`${field} must be between ${min} and ${max} characters.`);
      return undefined;
    }
    return text;
  }

  const title = checkText('title', 3, 80);
  const category = checkText('category', 2, 40);
  const description = checkText('description', 5, 300);

  let status = source.status;
  if (status === undefined || status === null) {
    errors.push('status is required.');
    status = undefined;
  } else if (typeof status !== 'string' || !VALID_STATUSES.includes(status)) {
    errors.push(`status must be exactly one of: ${VALID_STATUSES.map((s) => `'${s}'`).join(', ')}.`);
    status = undefined;
  }

  return { errors, value: { title, category, description, status } };
}

/** Parse and validate the :id route parameter (positive whole number). */
function parseId(raw) {
  if (!/^\d+$/.test(raw)) return null;
  const id = Number(raw);
  if (!Number.isSafeInteger(id) || id < 1 || id > MAX_PG_INT) return null;
  return id;
}

// GET /api/records - list all records
router.get('/', async (req, res, next) => {
  try {
    const result = await pool.query(
      'SELECT id, title, category, description, status FROM records ORDER BY id ASC'
    );
    res.status(200).json(result.rows);
  } catch (err) {
    next(err);
  }
});

// GET /api/records/:id - one record
router.get('/:id', async (req, res, next) => {
  try {
    const id = parseId(req.params.id);
    if (id === null) {
      return res.status(400).json({ error: 'Invalid id. It must be a positive whole number.' });
    }
    const result = await pool.query(
      'SELECT id, title, category, description, status FROM records WHERE id = $1',
      [id]
    );
    if (result.rows.length === 0) {
      return res.status(404).json({ error: `Record with id ${id} was not found.` });
    }
    res.status(200).json(result.rows[0]);
  } catch (err) {
    next(err);
  }
});

// POST /api/records - create a record (id is generated by the database)
router.post('/', async (req, res, next) => {
  try {
    const { errors, value } = validateRecord(req.body);
    if (errors.length > 0) {
      return res.status(400).json({ error: 'Validation failed.', details: errors });
    }
    const result = await pool.query(
      `INSERT INTO records (title, category, description, status)
       VALUES ($1, $2, $3, $4)
       RETURNING id, title, category, description, status`,
      [value.title, value.category, value.description, value.status]
    );
    res.status(201).json(result.rows[0]);
  } catch (err) {
    next(err);
  }
});

// PUT /api/records/:id - replace a record's fields
router.put('/:id', async (req, res, next) => {
  try {
    const id = parseId(req.params.id);
    if (id === null) {
      return res.status(400).json({ error: 'Invalid id. It must be a positive whole number.' });
    }
    const { errors, value } = validateRecord(req.body);
    if (errors.length > 0) {
      return res.status(400).json({ error: 'Validation failed.', details: errors });
    }
    const result = await pool.query(
      `UPDATE records
       SET title = $1, category = $2, description = $3, status = $4
       WHERE id = $5
       RETURNING id, title, category, description, status`,
      [value.title, value.category, value.description, value.status, id]
    );
    if (result.rows.length === 0) {
      return res.status(404).json({ error: `Record with id ${id} was not found.` });
    }
    res.status(200).json(result.rows[0]);
  } catch (err) {
    next(err);
  }
});

// DELETE /api/records/:id - remove a record
router.delete('/:id', async (req, res, next) => {
  try {
    const id = parseId(req.params.id);
    if (id === null) {
      return res.status(400).json({ error: 'Invalid id. It must be a positive whole number.' });
    }
    const result = await pool.query(
      'DELETE FROM records WHERE id = $1 RETURNING id, title, category, description, status',
      [id]
    );
    if (result.rows.length === 0) {
      return res.status(404).json({ error: `Record with id ${id} was not found.` });
    }
    res.status(200).json({ message: 'Record deleted.', record: result.rows[0] });
  } catch (err) {
    next(err);
  }
});

module.exports = router;
